export const topicById = id => BASHO_TOPICS.find(topic => topic.id === id);
// Dates already shown keep their verse: six topics before 2026-10-30, the first sixty in order until 2026-11-18,
// and from 2026-11-19 a verse of the date's season, by month: 3-5 spring, 6-8 summer, 9-11 autumn, 12-2 winter.
// Each topic's season is that of its 季語 (new-year verses sit in winter so that they appear in January).
// Until 2026-11-30 the season draws on the first sixty topics only. From 2026-12-01 all topics are used:
// a verse tied to a day appears on that day, the other verses of the season fill the remaining days in
// catalogue order from the season's first day, and no verse returns within the same year.
const FIRST_TOPICS = 60;
const EXPANDED_START = Date.parse('2026-10-30T00:00:00Z') / 86400000;
const SEASONAL_START = Date.parse('2026-11-19T00:00:00Z') / 86400000;
const FULL_POOL_START = Date.parse('2026-12-01T00:00:00Z') / 86400000;
const SEASON_OF_MONTH = ['winter', 'winter', 'spring', 'spring', 'spring', 'summer', 'summer', 'summer', 'autumn', 'autumn', 'autumn', 'winter'];
const SEASON_FIRST_MONTH = { spring: 2, summer: 5, autumn: 8, winter: 11 };
export const seasonOf = day => SEASON_OF_MONTH[Number(String(day).slice(5, 7)) - 1];
// Verses that belong to one day of the year: 元日, 二日, 七草, 立春から九日目ごろ, 雛祭り, 七夕, 重陽, 大晦日.
export const FIXED_DAYS = {
  '01-01': 'basho-ganjitsu-tagoto', '01-02': 'basho-futsuka', '01-07': 'basho-wakana', '02-12': 'basho-harutachite',
  '03-03': 'basho-kusanoto-hina', '07-07': 'basho-araumi', '09-09': 'basho-kikunosake', '12-31': 'basho-toshikurenu',
};
// 中秋の名月 (旧暦8月15日) and 十三夜 (旧暦9月13日) fall on a different day each year; 十六夜 is the day after 中秋.
// Years outside this table have no moon days and those verses simply take their turn in autumn. Extend it as needed.
export const MOON_DAYS = { 2027: ['09-15', '10-12'], 2028: ['10-03', '10-30'], 2029: ['09-22', '10-20'], 2030: ['09-12', '10-09'], 2031: ['10-01', '10-28'] };
const isoDay = n => new Date(n * 86400000).toISOString().slice(0, 10);
const pinCache = new Map();
// Map of 'YYYY-MM-DD' to topic id for one calendar year. A day holds one verse and a verse one day; the moon comes first.
function pinnedDays(year) {
  if (pinCache.has(year)) return pinCache.get(year);
  const pins = new Map(), used = new Set();
  const put = (day, id) => { if (!pins.has(day) && !used.has(id) && topicById(id)) { pins.set(day, id); used.add(id); } };
  const moon = MOON_DAYS[year];
  if (moon) {
    put(`${year}-${moon[0]}`, 'basho-meigetsu-ike');
    put(isoDay(Date.parse(`${year}-${moon[0]}T00:00:00Z`) / 86400000 + 1), 'basho-izayoi-ebi');
    put(`${year}-${moon[1]}`, 'basho-nochi-no-tsuki');
  }
  for (const [monthDay, id] of Object.entries(FIXED_DAYS)) put(`${year}-${monthDay}`, id);
  pinCache.set(year, pins);
  return pins;
}
export function dailyTopic(day) {
  const n = Date.parse(`${day}T00:00:00Z`) / 86400000;
  if (!Number.isInteger(n)) throw new Error('Invalid topic date');
  if (n >= SEASONAL_START) {
    const season = seasonOf(day), year = Number(day.slice(0, 4)), month = Number(day.slice(5, 7)) - 1;
    const startYear = season === 'winter' && month < 2 ? year - 1 : year;
    const start = Date.UTC(startYear, SEASON_FIRST_MONTH[season], 1) / 86400000;
    if (n < FULL_POOL_START) {
      const pool = BASHO_TOPICS.slice(0, FIRST_TOPICS).filter(topic => topic.season === season);
      return pool[(n - start) % pool.length];
    }
    // Winter runs from December into the next year, so it looks at the pinned days of both years.
    const pins = new Map([...pinnedDays(startYear), ...(season === 'winter' ? pinnedDays(startYear + 1) : [])]);
    if (pins.has(day)) return topicById(pins.get(day));
    const pinned = new Set(pins.values());
    const pool = BASHO_TOPICS.filter(topic => topic.season === season && !pinned.has(topic.id));
    let index = 0;
    for (let d = start; d < n; d++) if (!pins.has(isoDay(d))) index++;
    return pool[index % pool.length];
  }
  const index = n < EXPANDED_START ? ((n % 6) + 6) % 6 : (6 + n - EXPANDED_START) % FIRST_TOPICS;
  return BASHO_TOPICS[index];
}
export function validateHaiku(value) {
  if (!value || !Array.isArray(value.lines) || value.lines.length !== 3 || value.lines.some(line => typeof line !== 'string' || !line.trim() || [...line].length > 40 || /[\n\r]/.test(line))) throw new Error('Invalid haiku');
  if (typeof value.observed !== 'string' || !value.observed.trim() || value.observed.length > 400) throw new Error('Invalid observation');
  return { lines: value.lines.map(line => line.trim()), observed: value.observed.trim() };
}
