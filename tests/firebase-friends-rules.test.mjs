import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import { createRequire } from 'node:module';
// Run with the Firebase Database Emulator. No production project credentials needed.
const enabled=!!process.env.FIREBASE_DATABASE_EMULATOR_HOST;
test('Firebase: Google identity, invitation-only membership and private photo ownership', {skip:!enabled},async()=>{
  const deps=process.env.FIREBASE_TEST_DEPS;
  const load=async name=>deps?import(pathToFileURL(`${deps}/node_modules/${name}`).href):import(name);
  const {initializeTestEnvironment,assertSucceeds,assertFails}=await load('@firebase/rules-unit-testing/dist/esm/index.esm.js');
  const {ref,get,set,update,remove,query,orderByChild,equalTo,onValue,startAt,endAt,limitToFirst}=await load('firebase/database/dist/esm/index.esm.js');
  const [host,port]=process.env.FIREBASE_DATABASE_EMULATOR_HOST.split(':');
  const env=await initializeTestEnvironment({projectId:'demo-basho-friends',database:{host,port:Number(port),rules:await readFile(new URL('../firebase/database.rules.json',import.meta.url),'utf8')}});
  try{
    await env.clearDatabase();
    const google=name=>env.authenticatedContext(name,{firebase:{sign_in_provider:'google.com'},name}).database();
    const alice=google('alice'),bob=google('bob'),eve=google('eve'),anon=env.unauthenticatedContext().database();
    const password=env.authenticatedContext('password',{firebase:{sign_in_provider:'password'}}).database();
    const time=()=>Date.now();
    await assertFails(get(ref(anon,'groups')));
    // FCM tokens are server-only, including for signed-in owners.
    for(const client of [anon,alice,bob]){
      await assertFails(get(ref(client,'fcmDevices')));
      await assertFails(set(ref(client,'fcmDevices/test-device'),{uid:'alice',token:'private-token'}));
    }
    await assertFails(set(ref(password,'groups/wrong'),{owner:'password',createdAt:time(),members:{password:{name:'password',joinedAt:time()}}}));
    await assertSucceeds(set(ref(alice,'groups/friends'),{owner:'alice',createdAt:time(),members:{alice:{name:'Alice',joinedAt:time()}}}));
    await assertFails(get(ref(bob,'groups/friends')));
    await assertFails(set(ref(bob,'groups/friends/members/bob'),{name:'Bob',joinedAt:time()}));
    // Execute the real callable handlers against the emulator, never a real project.
    process.env.FIREBASE_DATABASE_URL='https://demo-basho-friends.firebaseio.com';
    const fcm=await import('../firebase/functions/index.mjs');
    const auth=uid=>({uid,token:{firebase:{sign_in_provider:'google.com'}}});
    const fcmData={deviceId:'e'.repeat(32),token:'emulator_token_'.repeat(10)};
    await fcm.fcmRegisterDevice.run({auth:auth('alice'),data:fcmData});
    assert.equal((await fcm.fcmDeviceStatus.run({auth:auth('alice'),data:fcmData})).enabled,true);
    const otherStatus=await fcm.fcmDeviceStatus.run({auth:auth('bob'),data:fcmData});
    assert.equal(otherStatus.enabled,false);assert.equal(otherStatus.token,undefined);
    await assert.rejects(fcm.fcmDisableDevice.run({auth:auth('bob'),data:fcmData}),error=>error.code==='permission-denied');
    await assert.rejects(fcm.fcmRegisterDevice.run({auth:auth('bob'),data:{...fcmData,token:'other_emulator_token_'.repeat(8)}}),error=>error.code==='permission-denied');
    // Separate Admin app instances reproduce cold Cloud Functions caches.
    const requireAdmin=createRequire(new URL('../firebase/functions/package.json',import.meta.url));
    const adminApp=requireAdmin('firebase-admin/app'),adminDB=requireAdmin('firebase-admin/database');
    const cold=adminApp.initializeApp({projectId:'demo-basho-friends',databaseURL:process.env.FIREBASE_DATABASE_URL},'cold-fcm');
    const coldRef=adminDB.getDatabase(cold).ref('fcmDevices/'+fcmData.deviceId);
    const {deliverDevice}=await import('../firebase/functions/delivery.mjs');let sent=0;
    const record={token:fcmData.token,updatedAt:Date.now(),enabled:true};
    assert.equal(await deliverDevice(coldRef,record,'morning','2026-11-17',{send:async()=>sent++}),'sent');
    assert.equal(await deliverDevice(coldRef,record,'morning','2026-11-17',{send:async()=>sent++}),'skipped');
    assert.equal(sent,1);
    await fcm.fcmDisableDevice.run({auth:auth('alice'),data:fcmData});
    assert.equal((await fcm.fcmDeviceStatus.run({auth:auth('alice'),data:fcmData})).enabled,false);
    // .info belongs to the SDK-local tree: verify the actual SDK listener path.
    const { friendsServerNow, readFriendsMembership }=await import('../firebase-friends.js');
    assert.equal(await readFriendsMembership({db:alice,dbSDK:{ref,get}},'friends','alice'),true);
    assert.equal(await readFriendsMembership({db:alice,dbSDK:{ref,get}},'missing-group','alice'),false);
    const serverNow=await friendsServerNow({db:alice,dbSDK:{ref,onValue}});
    assert.ok(Math.abs(serverNow-Date.now())<10000);
    await assertSucceeds(set(ref(alice,`invites/${'9'.repeat(64)}`),{groupId:'friends',owner:'alice',expiresAt:serverNow+7*86400000-60000}));
    const token='a'.repeat(64),other='b'.repeat(64),expired='c'.repeat(64);
    await assertSucceeds(set(ref(alice,`invites/${token}`),{groupId:'friends',owner:'alice',expiresAt:time()+86400000}));
    await assertFails(get(ref(anon,`invites/${token}`)));
    await assertFails(get(ref(bob,'invites')));
    await assertSucceeds(get(ref(bob,`invites/${token}`)));
    await assertSucceeds(set(ref(bob,'groups/friends/members/bob'),{name:'Bob',joinedAt:time(),invite:token}));
    await assertSucceeds(get(ref(bob,'groups/friends')));
    await assertSucceeds(set(ref(alice,'userGroups/alice'),{groupId:'friends'}));
    await assertSucceeds(set(ref(bob,'userGroups/bob'),{groupId:'friends'}));
    assert.equal((await get(ref(alice,'userGroups/alice'))).val().groupId,'friends');
    await assertFails(get(ref(bob,'userGroups/alice')));
    await assertFails(get(ref(anon,'userGroups/alice')));
    await assertFails(get(ref(password,'userGroups/alice')));
    await assertFails(get(ref(alice,'userGroups')));
    await assertFails(set(ref(bob,'userGroups/alice'),{groupId:'friends'}));
    await assertFails(set(ref(eve,'userGroups/eve'),{groupId:'friends'}));
    await assertFails(set(ref(alice,'userGroups/alice'),{groupId:'missing'}));
    await assertFails(set(ref(alice,'userGroups/alice'),{groupId:'friends',extra:'no'}));
    const {readFriendsMembers}=await import('../firebase-friends.js');
    const members=await readFriendsMembers({db:bob,dbSDK:{ref,get}},'friends','bob');
    assert.equal(members.length,2);
    assert.ok(members.some(member=>member.name==='Bob'&&member.own));
    assert.ok(members.some(member=>member.name==='Alice'&&!member.own));
    assert.ok(members.every(member=>!('invite' in member)));
    await assertFails(readFriendsMembers({db:eve,dbSDK:{ref,get}},'friends','eve'));
    await assertFails(readFriendsMembers({db:anon,dbSDK:{ref,get}},'friends','anon'));
    await assertFails(readFriendsMembers({db:password,dbSDK:{ref,get}},'friends','password'));
    await assertSucceeds(set(ref(bob,`invites/${other}`),{groupId:'friends',owner:'bob',expiresAt:time()+86400000}));
    await assertFails(set(ref(eve,`invites/${'e'.repeat(64)}`),{groupId:'friends',owner:'eve',expiresAt:time()+86400000}));
    await env.withSecurityRulesDisabled(async c=>set(ref(c.database(),`invites/${expired}`),{groupId:'friends',owner:'alice',expiresAt:time()-1}));
    await assertFails(set(ref(eve,'groups/friends/members/eve'),{name:'Eve',joinedAt:time(),invite:expired}));
    await assertFails(set(ref(eve,'groups/friends/members/eve'),{name:'Eve',joinedAt:time(),invite:'f'.repeat(64)}));
    await assertFails(set(ref(bob,'groups/friends/members/eve'),{name:'Eve',joinedAt:time(),invite:token}));
    await assertSucceeds(set(ref(alice,'groups/other'),{owner:'alice',createdAt:time(),members:{alice:{name:'Alice',joinedAt:time()}}}));
    await assertFails(readFriendsMembers({db:bob,dbSDK:{ref,get}},'other','bob'));
    await assertFails(set(ref(bob,'userGroups/bob'),{groupId:'other'}));
    await assertFails(set(ref(eve,'groups/other/members/eve'),{name:'Eve',joinedAt:time(),invite:token}));
    const path='groups/friends/photos/2026-11-16_alice';
    const photo={author:'alice',name:'Alice',createdAt:time(),day:'2026-11-16',topicId:'test-topic',caption:'光',image:'data:image/png;base64,AAAA'};
    await assertSucceeds(set(ref(alice,path),photo));
    await assertFails(get(ref(eve,path)));
    await assertFails(get(ref(anon,path)));
    await assertSucceeds(get(query(ref(bob,'groups/friends/photos'),orderByChild('day'),equalTo('2026-11-16'))));
    await assertFails(update(ref(bob,path),{caption:'改ざん'}));
    await assertFails(update(ref(bob,path),{author:'bob'}));
    await assertFails(remove(ref(bob,path)));
    const comment=`${path}/comments/${'d'.repeat(32)}`;
    await assertSucceeds(set(ref(bob,comment),{author:'bob',name:'Bob',text:'すてき',createdAt:time()}));
    await assertFails(update(ref(alice,comment),{text:'改ざん'}));
    await assertFails(remove(ref(alice,comment)));
    await assertSucceeds(set(ref(bob,`${path}/stamps/heart/bob`),true));
    await assertFails(set(ref(alice,`${path}/stamps/heart/bob`),true));
    await assertFails(set(ref(bob,`${path}/stamps/unknown/bob`),true));
    await assertFails(set(ref(eve,`${path}/stamps/heart/eve`),true));
    await assertSucceeds(update(ref(alice,path),{caption:'更新',createdAt:time()}));
    assert.equal((await get(ref(bob,comment))).val().text,'すてき');
    await assertFails(set(ref(alice,'groups/friends/photos/oversize'),{...photo,image:'data:image/png;base64,'+'A'.repeat(1100000)}));
    await assertFails(set(ref(alice,'groups/friends/photos/url'),{...photo,image:'https://example.com/photo.png'}));
    await assertSucceeds(remove(ref(bob,comment)));
    await assertSucceeds(remove(ref(bob,`${path}/stamps/heart/bob`)));
    // Historical calendar pages include both friends and retain same-day cursors.
    const {readSharedCalendar}=await import('../sharing-calendar.js');
    const pastDay='2026-10-12';
    for(let n=0;n<63;n++)await assertSucceeds(set(ref(alice,`groups/friends/photos/old_${String(n).padStart(3,'0')}`),{...photo,day:pastDay,createdAt:time()}));
    await assertSucceeds(set(ref(bob,'groups/friends/photos/bob_old'),{...photo,author:'bob',name:'Bob',day:'2026-10-20',createdAt:time()}));
    const sdk={ref,get,query,orderByChild,startAt,endAt,limitToFirst};
    const first=await readSharedCalendar({db:bob,dbSDK:sdk},'friends','2026-10');
    assert.equal(first.posts.length,60);assert.ok(first.nextCursor);assert.ok(first.posts.every(p=>p.day.startsWith('2026-10')));
    const rest=await readSharedCalendar({db:bob,dbSDK:sdk},'friends','2026-10',first.nextCursor);
    assert.equal(rest.posts.length,4);assert.equal(rest.nextCursor,null);
    assert.equal(new Set([...first.posts,...rest.posts].map(p=>p.id)).size,64);
    assert.ok(rest.posts.some(p=>p.author==='bob'));
    await assertFails(readSharedCalendar({db:eve,dbSDK:sdk},'friends','2026-10'));
    await assertFails(readSharedCalendar({db:anon,dbSDK:sdk},'friends','2026-10'));
    await assertFails(readSharedCalendar({db:bob,dbSDK:sdk},'other','2026-10'));
    await assertSucceeds(update(ref(alice,'groups/friends/photos/old_000'),{caption:'過去写真を更新',createdAt:time()}));
    await assertSucceeds(remove(ref(alice,path)));
    await assertFails(set(ref(bob,`${path}/stamps/heart/bob`),true));
    await assertFails(set(ref(alice,'groups/smuggled'),{owner:'alice',createdAt:time(),members:{alice:{name:'Alice',joinedAt:time()},eve:{name:'Eve',joinedAt:time()}}}));
  }finally{
    const require=createRequire(new URL('../firebase/functions/package.json',import.meta.url));
    const {getApps,deleteApp}=require('firebase-admin/app');
    await Promise.all(getApps().map(app=>deleteApp(app)));
    await env.cleanup();
  }
});
